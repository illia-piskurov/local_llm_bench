def is_balanced(s: str) -> bool:
    """
    Проверяет сбалансированность скобок в строке.
    Учитываются только скобки: (), [], {}.
    """
    stack = []
    mapping = {")": "(", "]": "[", "}": "{"}

    for char in s:
        if char in "([{":
            # Открывающая скобка: добавляем в стек
            stack.append(char)
        elif char in ")]}":
            # Закрывающая скобка
            # 1. Если стек пуст, значит закрывающая скобка без открывающей
            if not stack:
                return False
            
            # 2. Извлекаем последнюю открытую скобку
            top_element = stack.pop()
            
            # 3. Проверяем, соответствует ли она ожидаемой открывающей скобке
            if mapping[char] != top_element:
                return False
        
        # Игнорируем все остальные символы

    # Если после прохода стек пуст, значит все скобки закрыты корректно
    return not stack
