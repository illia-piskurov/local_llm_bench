from pathlib import Path

import cron_bench
from benchmarks.base import Benchmark, Level, TestResult

LEVEL1_PROMPT = """\
Реализуй парсер 5-позиционных cron-выражений и планировщик следующих запусков в одном Python файле.

Формат cron-выражения (строка из 5 полей через пробел):
<минута> <час> <день_месяца> <месяц> <день_недели>

Допустимые диапазоны:
- минута: 0-59
- час: 0-23
- день месяца: 1-31
- месяц: 1-12
- день недели: 0-6 (0 = Воскресенье, 1 = Понедельник, ..., 6 = Суббота)

Поддерживаемый синтаксис для каждого поля:
- `*` — любое допустимое значение
- Точное число, например: `5`
- Списки через запятую, например: `0,15,30,45`
- Диапазоны через дефис (включительно), например: `9-17` или `1-5`

Требования:
- Один файл, без внешних зависимостей (только стандартная библиотека Python: `datetime`, `calendar` и т.д.).
- Добавь функцию `next_runs(cron: str, from_time: str, count: int) -> list[str]`.
  - `cron`: строка с cron-выражением.
  - `from_time`: начальная дата-время в формате ISO 8601 UTC (например, `"2026-08-18T10:00:00.000Z"`).
  - `count`: количество следующих моментов запуска.
  - Возвращает список из `count` строк формата ISO 8601 UTC (`"YYYY-MM-DDTHH:MM:SS.000Z"`), строго позже `from_time`, упорядоченных по возрастанию времени. Секунды и миллисекунды равны `00:00.000Z`.

В ответе верни только код одним блоком ```python ... ```, без дополнительных пояснений вне блока.
"""

LEVEL2_PROMPT = """\
Дополни свою реализацию поддержкой шагов и стандартного правила дня месяца / дня недели:

1. Шаги (step):
   - `*/<n>` — каждое n-е значение в допустимом диапазоне поля (например, `*/15` для минут -> `0, 15, 30, 45`).
   - `<range>/<n>` — шаг n внутри диапазона (например, `10-20/5` -> `10, 15, 20` или `1-5/2` -> `1, 3, 5`).

2. Правило Cron V7 для дня месяца (day-of-month) и дня недели (day-of-week):
   - Если ОБА поля (день месяца и день недели) не являются `*`, то день считается подходящим, если выполняется ХОТЯ БЫ ОДНО из них (логическое OR).
   - Если хотя бы одно из полей равно `*`, применяется строгое совпадение по второму полю.

Не меняй поведение уже реализованных конструкций и сохрани сигнатуру `next_runs(cron: str, from_time: str, count: int) -> list[str]`.

В ответе верни только код одним блоком ```python ... ```, без дополнительных пояснений вне блока.
"""

LEVEL3_PROMPT = """\
Дополни свою реализацию поддержкой именованных макросов (алиасов) и корректной обработкой високосных годов:

1. Именованные макросы:
   - `@hourly`   -> эквивалент `0 * * * *`
   - `@daily`    -> эквивалент `0 0 * * *`
   - `@midnight` -> эквивалент `0 0 * * *`
   - `@weekly`   -> эквивалент `0 0 * * 0` (каждое воскресенье в 00:00)
   - `@monthly`  -> эквивалент `0 0 1 * *`
   - `@yearly`   -> эквивалент `0 0 1 1 *`
   - `@annually` -> эквивалент `0 0 1 1 *`

2. Календарные границы:
   - Корректная обработка 29 февраля в високосные годы (например, `0 12 29 2 *` должен находить только високосные годы: 2028, 2032 и т.д.).
   - Корректный переход через границу года (31 декабря 23:59 -> 1 января следующего года).

Не меняй поведение уже реализованных конструкций и сохрани сигнатуру `next_runs(cron: str, from_time: str, count: int) -> list[str]`.

В ответе верни только код одним блоком ```python ... ```, без дополнительных пояснений вне блока.
"""


class CronBenchmark(Benchmark):
    id = "cron"
    name = "Парсер Cron и планировщик дат (next_runs)"
    short = "Cron"
    levels = [
        Level(id="level1", name="Level 1 (базовые поля, списки, диапазоны)", prompt=LEVEL1_PROMPT, requires=None),
        Level(id="level2", name="Level 2 (шаги */n и OR-логика Dom/Dow)", prompt=LEVEL2_PROMPT, requires="level1"),
        Level(id="level3", name="Level 3 (алиасы @hourly/@daily и високосные переходы)", prompt=LEVEL3_PROMPT, requires="level2"),
    ]

    def run_tests(self, level_id: str, answer_path: Path) -> TestResult:
        if level_id == "level1":
            tests = cron_bench.LEVEL1_TESTS
        elif level_id == "level2":
            tests = cron_bench.LEVEL1_TESTS + cron_bench.LEVEL2_TESTS
        else:
            tests = cron_bench.LEVEL1_TESTS + cron_bench.LEVEL2_TESTS + cron_bench.LEVEL3_TESTS
        name = self.level_by_id(level_id).name
        try:
            cron_bench.load_next_runs(str(answer_path))
        except Exception as e:
            return TestResult(0, len(tests), [f"не удалось загрузить решение: {e}"])
        passed, total, failures = cron_bench.run_suite(name, tests, str(answer_path))
        return TestResult(passed, total, failures)
